using Drawing = System.Drawing;
using Drawing2D = System.Drawing.Drawing2D;
using Forms = System.Windows.Forms;

namespace Markshot.Core;

public sealed class TrayService : IDisposable
{
    private readonly Forms.NotifyIcon _notifyIcon;
    private readonly Func<System.Windows.Controls.ContextMenu> _buildMenu;
    private Window? _menuHost;
    private bool _disposed;

    public TrayService(
        Action capture,
        Action pin,
        Action restoreLastPin,
        Action settings,
        Action disableClickThrough,
        Action exit,
        Func<bool>? canRestore = null,
        Func<bool>? anyClickThrough = null)
    {
        // The tray menu is a WPF menu in the app's dark rounded style (not the system one),
        // rebuilt on each open so it only lists what applies right now.
        _buildMenu = () =>
        {
            var menu = new System.Windows.Controls.ContextMenu();
            void Add(string header, Action action, string? gesture = null)
            {
                var item = new System.Windows.Controls.MenuItem { Header = header, InputGestureText = gesture ?? "" };
                item.Click += (_, _) => action();
                menu.Items.Add(item);
            }

            Add("截图", capture, App.Config?.CaptureHotkey);
            Add("贴图剪贴板", pin, App.Config?.PinHotkey);
            if (canRestore?.Invoke() ?? true)
            {
                Add("恢复最近贴图", restoreLastPin, App.Config?.RestorePinHotkey);
            }

            if (anyClickThrough?.Invoke() ?? false)
            {
                Add("取消所有鼠标穿透", disableClickThrough);
            }

            menu.Items.Add(new System.Windows.Controls.Separator());
            Add("设置…", settings);
            menu.Items.Add(new System.Windows.Controls.Separator());
            Add("退出", exit);
            return menu;
        };

        _notifyIcon = new Forms.NotifyIcon
        {
            Icon = CreateIcon(),
            Text = "Markshot · 截图 / 贴图 / 翻译",
            Visible = true
        };

        _notifyIcon.DoubleClick += (_, _) => capture();
        // Middle click on the tray icon starts a capture right away.
        _notifyIcon.MouseUp += (_, e) =>
        {
            if (e.Button == Forms.MouseButtons.Middle)
            {
                capture();
            }
            else if (e.Button == Forms.MouseButtons.Right)
            {
                ShowMenu();
            }
        };
    }

    /// <summary>Opens the menu at the pointer (it flips up / left to stay on screen, above the taskbar).</summary>
    private void ShowMenu()
    {
        try
        {
            // A tiny invisible foreground window: without it the menu would not close when
            // clicking elsewhere (tray-menu rule of Windows).
            _menuHost ??= new Window
            {
                WindowStyle = WindowStyle.None,
                AllowsTransparency = true,
                Background = System.Windows.Media.Brushes.Transparent,
                ShowInTaskbar = false,
                Topmost = true,
                Width = 1,
                Height = 1,
                Left = -32000,
                Top = -32000
            };
            _menuHost.Show();
            _menuHost.Activate();
            Native.SetForegroundWindow(new System.Windows.Interop.WindowInteropHelper(_menuHost).Handle);

            var menu = _buildMenu();
            var cursor = Native.CursorPosition();
            var dpi = System.Windows.Media.VisualTreeHelper.GetDpi(_menuHost);
            menu.Placement = System.Windows.Controls.Primitives.PlacementMode.AbsolutePoint;
            menu.HorizontalOffset = cursor.X / dpi.DpiScaleX;
            menu.VerticalOffset = cursor.Y / dpi.DpiScaleY;
            menu.PlacementTarget = _menuHost;
            menu.Closed += (_, _) => _menuHost?.Hide();
            menu.IsOpen = true;
        }
        catch (Exception ex)
        {
            Log.Error("打开托盘菜单失败", ex);
        }
    }

    public void ShowBalloon(string title, string text)
    {
        try
        {
            _notifyIcon.BalloonTipTitle = title;
            _notifyIcon.BalloonTipText = text;
            _notifyIcon.ShowBalloonTip(3000);
        }
        catch (Exception ex)
        {
            Log.Error("显示托盘消息失败", ex);
        }
    }

    public void SetTooltip(string text)
    {
        try
        {
            _notifyIcon.Text = text.Length > 63 ? text[..63] : text;
        }
        catch
        {
            // Ignore tooltip failures.
        }
    }

    private static Drawing.Icon CreateIcon()
    {
        // The app logo (Assets/markshot.ico, generated by tools/make_icon.py) at the tray size.
        try
        {
            var resource = System.Windows.Application.GetResourceStream(
                new Uri("pack://application:,,,/Markshot;component/Assets/markshot.ico"));
            if (resource != null)
            {
                using var stream = resource.Stream;
                return new Drawing.Icon(stream, Forms.SystemInformation.SmallIconSize);
            }
        }
        catch (Exception ex)
        {
            Log.Error("加载托盘图标失败", ex);
        }

        return CreateFallbackIcon();
    }

    private static Drawing.Icon CreateFallbackIcon()
    {
        using var bitmap = new Drawing.Bitmap(32, 32);
        using (var graphics = Drawing.Graphics.FromImage(bitmap))
        {
            graphics.SmoothingMode = Drawing2D.SmoothingMode.AntiAlias;
            graphics.Clear(Drawing.Color.Transparent);

            using var path = RoundedRect(new Drawing.Rectangle(2, 2, 28, 28), 8);
            using var brush = new Drawing.SolidBrush(Drawing.Color.FromArgb(76, 141, 255));
            graphics.FillPath(brush, path);

            using var font = new Drawing.Font("Segoe UI", 16, Drawing.FontStyle.Bold, Drawing.GraphicsUnit.Pixel);
            using var format = new Drawing.StringFormat
            {
                Alignment = Drawing.StringAlignment.Center,
                LineAlignment = Drawing.StringAlignment.Center
            };
            graphics.DrawString("M", font, Drawing.Brushes.White, new Drawing.RectangleF(0, 1, 32, 32), format);
        }

        var handle = bitmap.GetHicon();
        try
        {
            using var temp = Drawing.Icon.FromHandle(handle);
            return (Drawing.Icon)temp.Clone();
        }
        finally
        {
            Native.DestroyIcon(handle);
        }
    }

    private static Drawing2D.GraphicsPath RoundedRect(Drawing.Rectangle bounds, int radius)
    {
        var path = new Drawing2D.GraphicsPath();
        var diameter = radius * 2;
        path.AddArc(bounds.X, bounds.Y, diameter, diameter, 180, 90);
        path.AddArc(bounds.Right - diameter, bounds.Y, diameter, diameter, 270, 90);
        path.AddArc(bounds.Right - diameter, bounds.Bottom - diameter, diameter, diameter, 0, 90);
        path.AddArc(bounds.X, bounds.Bottom - diameter, diameter, diameter, 90, 90);
        path.CloseFigure();
        return path;
    }

    public void Dispose()
    {
        if (_disposed)
        {
            return;
        }

        _disposed = true;
        _notifyIcon.Visible = false;
        _notifyIcon.Dispose();
        _menuHost?.Close();
    }
}
